// 根据分类名返回图标(资源卡片左上角)
export function categoryIcon(categoryKey: string, size = 18) {
  switch (categoryKey) {
    case "env":
      return <WifiIcon size={size} />;
    case "git":
      return <GitIcon size={size} />;
    case "task":
      return <TaskIcon size={size} />;
    case "proto":
      return <LayoutIcon size={size} />;
    default:
      return <FileIcon size={size} />;
  }
}
